import cv2

# ==============================
# 1. 打开摄像头
# ==============================
# 0 表示默认摄像头
# 如果电脑有多个摄像头，可以尝试改成 1、2、3……
cap = cv2.VideoCapture(3)

# ==============================
# 2. 检查摄像头是否打开成功
# ==============================
if not cap.isOpened():
    print("错误：无法打开摄像头！")
    exit()

print("摄像头启动成功！")
print("按 Q 键退出程序。")

# ==============================
# 3. 循环读取摄像头画面
# ==============================
while True:

    # 读取一帧画面
    ret, frame = cap.read()

    # 检查是否读取成功
    if not ret:
        print("错误：无法读取摄像头画面！")
        break

    # ==============================
    # 4. 显示摄像头画面
    # ==============================
    cv2.imshow("Camera", frame)

    # ==============================
    # 5. 按 Q 键退出
    # ==============================
    # waitKey(1) 表示等待 1ms
    # & 0xFF 用于兼容不同系统
    if cv2.waitKey(1) & 0xFF == ord('q'):
        break

# ==============================
# 6. 释放摄像头
# ==============================
cap.release()

# 关闭所有 OpenCV 窗口
cv2.destroyAllWindows()

print("摄像头已关闭。")